package com.generated.ldmurdergame.bootstrap;

import java.time.LocalDate;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * 排班域建表与种子数据。
 * DDL 同时兼容 PostgreSQL（Docker 部署）与 H2（本地文件库），
 * 因此不依赖 schema.sql 的方言差异；database/init.sql 仅作 PG 初始化镜像。
 */
@Component
@Order(0)
public class DataInitializer implements ApplicationRunner {
  private static final Logger log = LoggerFactory.getLogger(DataInitializer.class);

  private final JdbcTemplate jdbc;

  public DataInitializer(JdbcTemplate jdbc) {
    this.jdbc = jdbc;
  }

  @Override
  public void run(ApplicationArguments args) {
    createTables();
    seedDms();
    seedDemoShifts();
  }

  private void createTables() {
    jdbc.execute("""
      CREATE TABLE IF NOT EXISTS dm (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(80) NOT NULL,
        skills VARCHAR(400) NOT NULL DEFAULT ''
      )
      """);
    jdbc.execute("""
      CREATE TABLE IF NOT EXISTS dm_shift (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        work_date DATE NOT NULL,
        start_time VARCHAR(5) NOT NULL,
        required_skill VARCHAR(40) NOT NULL,
        required_count INT NOT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT uq_dm_shift_slot_skill UNIQUE (work_date, start_time, required_skill)
      )
      """);
    jdbc.execute("""
      CREATE TABLE IF NOT EXISTS shift_assignment (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        shift_id BIGINT NOT NULL,
        dm_id BIGINT NOT NULL,
        work_date DATE NOT NULL,
        start_time VARCHAR(5) NOT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT uq_assignment_dm_slot UNIQUE (dm_id, work_date, start_time)
      )
      """);
    jdbc.execute("""
      CREATE TABLE IF NOT EXISTS swap_request (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        from_shift_id BIGINT NOT NULL,
        from_work_date DATE NOT NULL,
        from_start_time VARCHAR(5) NOT NULL,
        required_skill VARCHAR(40) NOT NULL,
        to_shift_id BIGINT,
        to_work_date DATE,
        to_start_time VARCHAR(5),
        requester_id BIGINT NOT NULL,
        target_id BIGINT NOT NULL,
        status VARCHAR(12) NOT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
      """);
    jdbc.execute("""
      CREATE INDEX IF NOT EXISTS idx_shift_date ON dm_shift (work_date)
      """);
    jdbc.execute("""
      CREATE INDEX IF NOT EXISTS idx_assignment_shift ON shift_assignment (shift_id)
      """);
    jdbc.execute("""
      CREATE INDEX IF NOT EXISTS idx_swap_target_status ON swap_request (target_id, status)
      """);
  }

  private void seedDms() {
    Integer count = jdbc.queryForObject("SELECT COUNT(*) FROM dm", Integer.class);
    if (count != null && count > 0) {
      return;
    }
    record SeedDm(String name, String skills) {
    }
    List<SeedDm> seeds = List.of(
        new SeedDm("陈默", "硬核推理,阵营对抗"),
        new SeedDm("林晚", "情感沉浸,硬核推理"),
        new SeedDm("何惧", "恐怖机制,阵营对抗"),
        new SeedDm("周野", "欢乐机制,阵营对抗"),
        new SeedDm("苏念", "情感沉浸"),
        new SeedDm("高燃", "欢乐机制,恐怖机制,硬核推理"));
    for (SeedDm seed : seeds) {
      jdbc.update("INSERT INTO dm (name, skills) VALUES (?, ?)", seed.name(), seed.skills());
    }
    log.info("DM 排班：已初始化 {} 名 DM", seeds.size());
  }

  /** 预置今天起三天的示例班次，含满员班与缺口班，让排班台打开即有内容。 */
  private void seedDemoShifts() {
    Integer count = jdbc.queryForObject("SELECT COUNT(*) FROM dm_shift", Integer.class);
    if (count != null && count > 0) {
      return;
    }
    Map<String, Long> dmIds = new LinkedHashMap<>();
    jdbc.query("SELECT id, name FROM dm ORDER BY id", rs -> {
      dmIds.put(rs.getString("name"), rs.getLong("id"));
    });

    record SeedShift(String time, String skill, int need, List<String> dms) {
    }
    List<SeedShift> template = List.of(
        new SeedShift("14:00", "硬核推理", 2, List.of("陈默", "周野")),
        new SeedShift("14:00", "情感沉浸", 1, List.of("林晚")),
        new SeedShift("19:00", "恐怖机制", 2, List.of("何惧")),
        new SeedShift("19:00", "欢乐机制", 1, List.of()));

    for (int offset = 0; offset < 3; offset++) {
      LocalDate date = LocalDate.now().plusDays(offset);
      for (SeedShift seed : template) {
        jdbc.update(
            "INSERT INTO dm_shift (work_date, start_time, required_skill, required_count) VALUES (?, ?, ?, ?)",
            date, seed.time(), seed.skill(), seed.need());
        Long shiftId = jdbc.queryForObject(
            "SELECT id FROM dm_shift WHERE work_date = ? AND start_time = ? AND required_skill = ?",
            Long.class, date, seed.time(), seed.skill());
        for (String dmName : seed.dms()) {
          Long dmId = dmIds.get(dmName);
          if (shiftId != null && dmId != null) {
            jdbc.update(
                "INSERT INTO shift_assignment (shift_id, dm_id, work_date, start_time) VALUES (?, ?, ?, ?)",
                shiftId, dmId, date, seed.time());
          }
        }
      }
    }
    log.info("DM 排班：已初始化三天示例班次");
  }
}
