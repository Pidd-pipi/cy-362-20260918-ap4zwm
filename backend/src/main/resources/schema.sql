-- DM 排班台数据表（H2 PostgreSQL 模式与 PostgreSQL 通用）

CREATE TABLE IF NOT EXISTS dm (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(60) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dm_skill (
  dm_id BIGINT NOT NULL REFERENCES dm (id) ON DELETE CASCADE,
  skill VARCHAR(40) NOT NULL,
  PRIMARY KEY (dm_id, skill)
);

CREATE TABLE IF NOT EXISTS shift (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_date DATE NOT NULL,
  slot VARCHAR(8) NOT NULL,
  skill VARCHAR(40) NOT NULL,
  required_count INT NOT NULL,
  created_by VARCHAR(60),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_shift_slot CHECK (slot IN ('14:00', '19:00')),
  CONSTRAINT chk_shift_required_count CHECK (required_count >= 1)
);

CREATE TABLE IF NOT EXISTS shift_assignment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_id BIGINT NOT NULL REFERENCES shift (id) ON DELETE CASCADE,
  dm_id BIGINT NOT NULL REFERENCES dm (id),
  shift_date DATE NOT NULL,
  slot VARCHAR(8) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_assignment_shift_dm UNIQUE (shift_id, dm_id),
  CONSTRAINT uq_assignment_dm_slot UNIQUE (dm_id, shift_date, slot)
);

CREATE TABLE IF NOT EXISTS swap_request (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_id BIGINT NOT NULL REFERENCES shift (id) ON DELETE CASCADE,
  from_dm_id BIGINT NOT NULL REFERENCES dm (id),
  to_dm_id BIGINT REFERENCES dm (id),
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
  note VARCHAR(200),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_swap_status CHECK (status IN ('OPEN', 'ACCEPTED', 'COMPLETED', 'CANCELLED'))
);
